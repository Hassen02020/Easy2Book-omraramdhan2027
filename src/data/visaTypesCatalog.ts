export function getVisaCategoryByPageId(
  pageId: string,
  templateId?: string
): VisaCategoryLandingSpec {
  const byPage = VISA_TYPES_CATALOG.find((v) => v.pageId === pageId);
  if (byPage) return byPage;
  if (templateId) {
    const byTpl = VISA_TYPES_CATALOG.find((v) => v.templateId === templateId);
    if (byTpl) return byTpl;
  }
  if (pageId.includes('egypt')) return VISA_TYPES_CATALOG[0];
  if (pageId.includes('schengen') || pageId.includes('france'))
    return VISA_TYPES_CATALOG[1];
  if (pageId.includes('dubai')) return VISA_TYPES_CATALOG[2];
  if (pageId.includes('qatar')) return VISA_TYPES_CATALOG[3];
  if (pageId.includes('oman')) return VISA_TYPES_CATALOG[4];
  if (pageId.includes('omra')) return VISA_TYPES_CATALOG[5];
  if (pageId.includes('international') || pageId.includes('chine'))
    return VISA_TYPES_CATALOG[6];
  if (pageId.includes('evisa') || pageId.includes('alban') || pageId.includes('thai'))
    return VISA_TYPES_CATALOG[7];
  return VISA_TYPES_CATALOG[0];
}
